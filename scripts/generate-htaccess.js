#!/usr/bin/env node
/*
 * Writes static/.htaccess (Gatsby copies static/ into public/) with the 301
 * redirects for the move to /<district>/ URLs. Re-run after enabling a district
 * in src/data/districts.json:   node scripts/generate-htaccess.js
 *
 *  1. Old district sub-domains (districts.json `legacyHost`, e.g.
 *     dhaka.rajdoctors.com) -> https://rajdoctors.com/<district>/...
 *     /doctor/x, /doctors/, /speciality/x, /emergency, / (and /bn/, /en/
 *     variants) move under /<district>/; any other path (teledoctor, about-us,
 *     assets, ...) goes to the same path on rajdoctors.com.
 *  2. The district that used to live at the root of rajdoctors.com
 *     (`legacyPaths: true`, Rajshahi): /doctor/x -> /rajshahi/doctor/x, etc.
 * Doctor slugs did not change, so a path maps 1:1.
 */
const fs = require("fs")
const path = require("path")

const root = path.join(__dirname, "..")
const { districts } = JSON.parse(fs.readFileSync(path.join(root, "src/data/districts.json"), "utf8"))
const MAIN = "rajdoctors.com"
const MOVED = "doctor|doctors|speciality|emergency" // per-district sections
const esc = s => s.replace(/\./g, "\\.")

const subdomains = districts.filter(d => d.enabled && d.legacyHost && d.legacyHost !== MAIN)
const rootDistrict = districts.find(d => d.enabled && d.legacyPaths)

const lines = [
  "# Generated by scripts/generate-htaccess.js from src/data/districts.json - do not edit by hand.",
  "# See docs/DISTRICTS.md.",
  "",
  "ErrorDocument 404 /404.html",
  "",
  "<IfModule mod_rewrite.c>",
  "RewriteEngine On",
  "",
]
for (const d of subdomains) {
  const host = `^(?:www\\.)?${esc(d.legacyHost)}$`
  lines.push(
    `# ${d.en}: ${d.legacyHost} -> ${MAIN}/${d.slug}/`,
    `RewriteCond %{HTTP_HOST} ${host} [NC]`,
    `RewriteRule ^((?:en|bn)/)?$ https://${MAIN}/$1${d.slug}/ [R=301,L]`,
    `RewriteCond %{HTTP_HOST} ${host} [NC]`,
    `RewriteRule ^((?:en|bn)/)?(${MOVED})(/.*)?$ https://${MAIN}/$1${d.slug}/$2$3 [R=301,L]`,
    `RewriteCond %{HTTP_HOST} ${host} [NC]`,
    `RewriteRule ^(.*)$ https://${MAIN}/$1 [R=301,L]`,
    ""
  )
}
if (rootDistrict) {
  lines.push(
    `# ${rootDistrict.en} used to be the root of ${MAIN}: /doctor/x -> /${rootDistrict.slug}/doctor/x`,
    `RewriteRule ^((?:en|bn)/)?(${MOVED})(/.*)?$ /$1${rootDistrict.slug}/$2$3 [R=301,L]`,
    ""
  )
}
lines.push("</IfModule>", "")
const out = path.join(root, "static", ".htaccess")
fs.mkdirSync(path.dirname(out), { recursive: true })
fs.writeFileSync(out, lines.join("\n"))
console.log(`wrote ${path.relative(root, out)}: ${subdomains.length} sub-domain(s), root district ${rootDistrict ? rootDistrict.slug : "none"}`)
